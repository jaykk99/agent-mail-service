#!/usr/bin/env python3
"""Stage a complete self-hosted Linux mail DNS + Postfix/Dovecot plan.

Never touches /etc, opens ports or fabricates DNS delegation. Use the staged
files only after reviewing with actual service versions and permissions.
"""
import argparse
import json
import os
from pathlib import Path
import shutil
import subprocess

try:
    from .dns_zone import zone_text, named_config, read_opendkim_public_txt
    from .generate_config import render, check_domain
except ImportError:
    from dns_zone import zone_text, named_config, read_opendkim_public_txt
    from generate_config import render, check_domain


def prepare(domain, data, public_ip, ns1_ip, ns2_ip, vmail_uid, vmail_gid,
            cert, key, output, dkim_public_txt=None):
    domain = check_domain(domain)
    data = Path(data).expanduser().resolve(strict=True)
    if not data.is_dir() or not os.access(data, os.W_OK):
        raise ValueError("The configured USB data directory must exist and be writable")
    cert = Path(cert).expanduser().resolve()
    key = Path(key).expanduser().resolve()
    if not cert.is_file() or not key.is_file():
        raise ValueError("Both TLS certificate and private key files must already exist")
    if cert == key:
        raise ValueError("Certificate and private key must be separate files")
    db = data / "agents.sqlite3"
    if not db.is_file():
        raise ValueError("Provision a mailbox first; the existing SQLite account DB is missing")
    # No automatic migration or copying of sensitive databases.
    import sqlite3
    with sqlite3.connect(f"file:{db}?mode=ro", uri=True) as connection:
        row = connection.execute(
            "SELECT value FROM config WHERE name='domain'"
        ).fetchone()
        if not row or row[0] != domain:
            raise ValueError("Existing mail accounts must belong to the chosen domain")
    templates = render(domain, str(db), str(data / "maildirs"), vmail_uid,
                       vmail_gid, str(cert), str(key), public_ip)
    public_key = read_opendkim_public_txt(dkim_public_txt) if dkim_public_txt else None
    dns = zone_text(domain, public_ip, ns1_ip, ns2_ip, public_key)
    destination = Path(output).expanduser().resolve()
    destination.mkdir(parents=True, exist_ok=True, mode=0o700)
    zone_file = destination / ("db." + domain)
    files = {**templates, zone_file.name: dns,
             "named.conf.monico": named_config(domain, zone_file)}
    for name, contents in files.items():
        target = destination / name
        if target.exists():
            raise FileExistsError(f"Refusing to overwrite staged file: {target}")
        target.write_text(contents, encoding="utf-8")
        target.chmod(0o600)
    validate_result = "not-installed"
    if shutil.which("named-checkzone"):
        check = subprocess.run(["named-checkzone", domain, str(zone_file)],
                               capture_output=True, text=True, timeout=15)
        validate_result = "passed" if check.returncode == 0 else "failed: " + check.stderr[-200:]
    manifest = {
        "status": "STAGED_NOT_DEPLOYED",
        "domain": domain,
        "mail_host": "mail." + domain,
        "usb_data_directory": str(data),
        "nameserver_validation": validate_result,
        "live_dns_verified": False,
        "public_inbound_smtp_verified": False,
        "public_outbound_smtp_verified": False,
        "tls_trust_verified": False,
        "dkim_public_key_embedded": bool(public_key),
        "requires": [
            "Authoritative domain delegation and nameserver glue at the parent",
            "Public TCP 53/25 and an IP with correct PTR reverse DNS",
            "Postfix and matching Dovecot version installed, configs reviewed",
            "Dovecot/SQLite/Maildir access by dedicated Linux mail users",
            "DKIM signing plus SPF/DMARC policy and anti-abuse controls",
            "Trusted TLS and end-to-end external mail delivery test",
        ],
    }
    (destination / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n",
                                                 encoding="utf-8")
    (destination / "manifest.json").chmod(0o600)
    return manifest


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--domain", required=True)
    p.add_argument("--data", required=True, help="Already mounted USB directory with account DB")
    p.add_argument("--public-ip", required=True, help="Globally routable IPv4")
    p.add_argument("--ns1-ip", required=True)
    p.add_argument("--ns2-ip", required=True)
    p.add_argument("--vmail-uid", type=int, required=True)
    p.add_argument("--vmail-gid", type=int, required=True)
    p.add_argument("--cert", required=True)
    p.add_argument("--key", required=True)
    p.add_argument("--dkim-public-txt", help="Public mail.txt generated by opendkim-genkey")
    p.add_argument("--output", default=".generated/live-stage")
    args = p.parse_args()
    manifest = prepare(args.domain, args.data, args.public_ip,
                       args.ns1_ip, args.ns2_ip, args.vmail_uid,
                       args.vmail_gid, args.cert, args.key, args.output,
                       args.dkim_public_txt)
    print(json.dumps(manifest, indent=2))
    print("No public mail service was started. Do not expose it until every requirement is verified.")


if __name__ == "__main__":
    main()
