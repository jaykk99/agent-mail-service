#!/usr/bin/env python3
"""Fail-closed checks before exposing self-hosted SMTP/IMAP.

Does not change the host or claim remote inbound TCP/25 is reachable.
"""
import argparse
import ipaddress
import json
import os
from pathlib import Path
import shutil
import socket
import sqlite3
import subprocess
import sys
import tempfile


def check_domain(domain):
    try:
        from .generate_config import check_domain as validated
    except ImportError:
        from generate_config import check_domain as validated
    return validated(domain)


def check_environment(data_dir, domain, host, public_ip, live=False):
    results = []

    def report(name, passed, reason, level="required"):
        results.append({"check": name, "passed": bool(passed), "level": level, "detail": reason})

    try:
        domain = check_domain(domain)
        report("delegated-format", True, "Domain name format is plausible; actual delegation must be checked separately")
    except ValueError as e:
        report("delegated-format", False, str(e))
    if host != f"mail.{domain}":
        report("hostname", False, "Expected mail.<domain> as generated by the Postfix template")
    else:
        report("hostname", True, host)

    ip = None
    try:
        ip = ipaddress.ip_address(public_ip)
        if ip.version != 4 or not ip.is_global:
            raise ValueError("IPv4 must be globally routable")
        report("public-ip", True, str(ip))
    except ValueError as e:
        report("public-ip", False, str(e))

    storage = Path(data_dir).expanduser().resolve()
    report("usb-path", "/mnt/chromeos/removable/" in str(storage) + "/" or str(storage).startswith("/mnt/"),
           "Verify this is a real mounted USB volume, not an internal folder or symlink",
           "warning")
    report("data-directory", storage.is_dir() and os.access(storage, os.W_OK),
           f"Directory must exist and be writable: {storage}")

    if storage.is_dir() and os.access(storage, os.W_OK):
        try:
            fd, path = tempfile.mkstemp(dir=storage, prefix=".monico-probe-", suffix=".sqlite3")
            os.close(fd)
            try:
                with sqlite3.connect(path, timeout=3) as con:
                    con.execute("CREATE TABLE test(id INTEGER PRIMARY KEY, value TEXT)")
                    con.execute("INSERT INTO test(value) VALUES ('ok')")
                    assert con.execute("SELECT value FROM test").fetchone()[0] == "ok"
            finally:
                for suffix in ("", "-journal", "-wal", "-shm"):
                    try:
                        os.unlink(path + suffix)
                    except FileNotFoundError:
                        pass
            report("sqlite-write", True, "SQLite insert and query succeeded on current storage")
        except (OSError, sqlite3.Error, AssertionError) as e:
            report("sqlite-write", False, f"{type(e).__name__}: {e}")
    else:
        report("sqlite-write", False, "Skipped: storage inaccessible")

    try:
        mounts = Path("/proc/mounts").read_text().splitlines()
        candidates = []
        for line in mounts:
            fields = line.split()
            if len(fields) >= 3 and (str(storage) == fields[1] or str(storage).startswith(fields[1].rstrip("/") + "/")):
                candidates.append((len(fields[1]), fields[2], fields[1]))
        fs = max(candidates)[1:] if candidates else ("unknown", "unknown")
        report("filesystem", fs[0] not in {"9p", "fuse", "fuse.virtiofs", "fuse.9p"},
               f"Underlying mount {fs[1]} type {fs[0]}; test POSIX ownership and locking for vmail",
               "warning")
    except OSError:
        report("filesystem", False, "Cannot inspect Linux mount type", "warning")

    for program in ("postfix", "postconf", "dovecot", "doveconf", "openssl"):
        report("binary-" + program, shutil.which(program) is not None,
               f"{program} must be installed on the host", "required" if live else "warning")

    if live:
        try:
            resolved = set(socket.gethostbyname_ex(host)[2])
            report("dns-host-a", str(ip) in resolved, f"{host} A addresses: {sorted(resolved)}")
        except (OSError, ValueError) as e:
            report("dns-host-a", False, str(e))
        dig = shutil.which("dig")
        if dig:
            def dig_records(*args):
                proc = subprocess.run([dig, "+short", *args], capture_output=True, text=True, timeout=12)
                return proc.stdout.strip().splitlines() if proc.returncode == 0 else []
            mx = dig_records("MX", domain)
            report("dns-mx", any(host.rstrip(".").lower() in row.rstrip(".").lower() for row in mx),
                   "MX " + repr(mx))
            ns = dig_records("NS", domain)
            report("dns-ns", bool(ns), "NS " + repr(ns))
            spf = dig_records("TXT", domain)
            report("dns-spf", any("v=spf1" in row for row in spf), "SPF TXT " + repr(spf))
            dmarc = dig_records("TXT", "_dmarc." + domain)
            report("dns-dmarc", any("v=DMARC1" in row for row in dmarc), "DMARC TXT " + repr(dmarc))
            ptr = dig_records("-x", public_ip)
            report("dns-ptr", any(row.rstrip(".").lower() == host.rstrip(".").lower() for row in ptr),
                   "PTR " + repr(ptr))
        else:
            for key in ("dns-mx", "dns-ns", "dns-spf", "dns-dmarc", "dns-ptr"):
                report(key, False, "Install dnsutils for authoritative record checks")
        for port in (587, 993):
            try:
                with socket.create_connection((host, port), timeout=3):
                    report("tcp-" + str(port), True, f"{host}:{port} reachable from this machine")
            except OSError as e:
                report("tcp-" + str(port), False, str(e))
        report("tcp25-external", False,
               "Cannot prove inbound TCP/25 from inside your LAN; test from an independent external network",
               "warning")
        report("dkim-signature", False,
               "Verify outbound DKIM signing separately; TXT existence alone is insufficient",
               "warning")
    else:
        report("dns-and-ports", False, "Run with --live when public DNS/host is configured",
               "warning")

    ready = all(item["passed"] for item in results if item["level"] == "required")
    return {"ready_for_next_setup_step": ready, "checks": results,
            "note": "Passing preflight does not prove external email delivery, TLS trust or spam acceptance"}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data", required=True, help="USB-mounted SQLite directory")
    parser.add_argument("--domain", required=True, help="Delegated public email domain")
    parser.add_argument("--host", required=True, help="Mail host (mail.<domain>)")
    parser.add_argument("--public-ip", required=True)
    parser.add_argument("--live", action="store_true", help="Also check public DNS and TCP ports")
    args = parser.parse_args()
    result = check_environment(args.data, args.domain, args.host, args.public_ip, args.live)
    print(json.dumps(result, indent=2))
    if not result["ready_for_next_setup_step"]:
        sys.exit(1)


if __name__ == "__main__":
    main()
